/// Expected payload: the UTF-8 encoding of code points U+00C8..U+00DB
/// (pdf417gen converts its input string to UTF-8 before byte compaction).
const EXPECTED_PAYLOAD: [u8; 40] = [
    195, 136, 195, 137, 195, 138, 195, 139, 195, 140, 195, 141, 195, 142, 195, 143, 195, 144, 195,
    145, 195, 146, 195, 147, 195, 148, 195, 149, 195, 150, 195, 151, 195, 152, 195, 153, 195, 154,
    195, 155,
];

#[test]
fn decodes_external_reference_symbol() {
    let matrix: alloc::vec::Vec<u8> = REFERENCE_MATRIX
        .iter()
        .flat_map(|row| row.bytes().map(|b| b - b'0'))
        .collect();
    let decoded = pdf417::decode(&matrix, 171, 8).unwrap();
    assert_eq!(decoded, EXPECTED_PAYLOAD);
}
